#!/usr/bin/env python3
"""Stage295 ROM-free repository: construct a TEMPORARY artificial Minivader ROM.

Purpose: exercise the real historical MAME 0.106 CPU, ROM loader and (when
available) video/record/playback loop in Windows GitHub Actions without any
copyrighted original ROM, including the user-provided dino files.

NEVER commit or upload the synthetic ROM or test-patched runtime, and NEVER
interpret successful Minivader test as original Cadillacs and Dinosaurs replay.
This changes the Minivader ROM_CHECKSUM in a disposable upstream source tree
for this diagnostic build only. Use only AFTER the production MAME executable
has been built and copied to its normal code-only artifact directory.
"""
import argparse
import hashlib
import json
import pathlib
import re
import zlib

SOURCE_FILE = "src/drivers/minivadr.c"
ORIGINAL_LINE = (
    '\tROM_LOAD( "d26-01.bin",\t0x0000, 0x2000, '
    'CRC(a96c823d) SHA1(aa9969ff80e94b0fff0f3530863f6b300510162e) )'
)
ROM_NAME = "d26-01.bin"
ROM_BYTES = 0x2000
# A synthetic Z80 program repeatedly changing a VISIBLE video RAM byte at
# 0xa200. Minivader vidhrdw maps offset / 32 to y, and visible y starts
# at 16: 0xa000 would be y=0 and produce a falsely static MNG.
# It is not derived from any original game.
# 0000: DI
# 0001: LD HL,0xa200
# 0004: LD A,0x01
# 0006: LD (HL),A
# 0007: INC A
# 0008: JP 0006
SYNTHETIC_Z80_PROGRAM = bytes.fromhex("f3 21 00 a2 3e 01 77 3c c3 06 00")


def generate(root, out_rom_root):
    root = pathlib.Path(root)
    out_rom_root = pathlib.Path(out_rom_root)
    driver = root / SOURCE_FILE
    if not driver.is_file() or driver.is_symlink():
        raise ValueError("missing regular historical Minivader source")
    old = driver.read_bytes()
    if b"\r\n" in old:
        raise ValueError("source must be LF-normalized before patching")
    text = old.decode("utf-8")
    if text.count(ORIGINAL_LINE) != 1:
        raise ValueError("expected exactly one original ROM checksum anchor")
    rom = SYNTHETIC_Z80_PROGRAM + b"\x00" * (
        ROM_BYTES - len(SYNTHETIC_Z80_PROGRAM))
    assert len(rom) == ROM_BYTES
    crc = f"{zlib.crc32(rom) & 0xffffffff:08x}"
    sha = hashlib.sha1(rom).hexdigest()
    new_line = (
        '\tROM_LOAD( "d26-01.bin",\t0x0000, 0x2000, '
        f'CRC({crc}) SHA1({sha}) )'
    )
    patched = text.replace(ORIGINAL_LINE, new_line, 1)
    # Keep generated byte content in isolated private temporary ROM paths.
    if out_rom_root.is_symlink() or out_rom_root.exists():
        raise ValueError("synthetic ROM output folder must not exist")
    if not out_rom_root.parent.is_dir():
        raise ValueError("synthetic ROM parent directory missing")
    destination = out_rom_root / "minivadr"
    destination.mkdir(parents=True, exist_ok=False)
    rom_path = destination / ROM_NAME
    with rom_path.open("xb") as handle:
        handle.write(rom)
    driver.write_text(patched, encoding="utf-8", newline="\n")
    return {
        "schema": "dino-stage295-synthetic-minivader-fixture-v1",
        "synthetic_game": "minivadr",
        "synthetic_rom_bytes": len(rom),
        "fixture_crc32": crc,
        "fixture_sha1": sha,
        "test_driver_source_modified": True,
        "actual_original_rom_or_inp_used": False,
        "original_dino_gameplay_verified": False,
        "original_mame_runtime_unchanged_after_test": False,
    }


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source-root", type=pathlib.Path, required=True)
    parser.add_argument("--rom-dir", type=pathlib.Path, required=True)
    args = parser.parse_args(argv)
    # Print ONLY synthetic checksum and status; no user private content.
    report = generate(args.source_root, args.rom_dir)
    print(json.dumps(report, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
