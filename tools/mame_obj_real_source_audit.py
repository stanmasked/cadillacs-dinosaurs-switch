#!/usr/bin/env python3
"""Fail-closed audit of generated MAME 0.289 C++ against exact upstream bytes.

This does not compile MAME. Both sources are read locally; only SHA digests
and structural results are printed, never the upstream C++ or game assets.
"""
import argparse
import hashlib
from pathlib import Path
import sys

try:
    from tools.mame_obj_source_probe import (
        EXPECTED_MAME_BLOB, INCLUDE, LATCH_HOOK, HOOK, PROBE,
        PROBE_MARKER, git_blob_sha,
    )
except ModuleNotFoundError:
    from mame_obj_source_probe import (
        EXPECTED_MAME_BLOB, INCLUDE, LATCH_HOOK, HOOK, PROBE,
        PROBE_MARKER, git_blob_sha,
    )

INCLUDE_ADDITION = (
    '#include <atomic>\n#include <cstdio>\n#include <cstring>\n#include <cstdlib>\n'
    'static std::atomic<unsigned long long> cps1_dino_obj_latch_events{0};\n'
)
LATCH_ADDITION = (
    '\t\tif (std::strcmp(machine().system().name, "dino") == 0)\n'
    '\t\t\tcps1_dino_obj_latch_events.fetch_add(1, std::memory_order_relaxed);\n'
)
VIDEO_UPDATE_ADDITION = (
    '\tfind_last_sprite();\n' + PROBE + '\n\tcps1_update_transmasks();'
)


def audit_original_and_generated(original, generated):
    """Require the exact tag and only three well-scoped code insertions.

    The original MAME source must be restored byte-for-byte by undoing the
    approved include, latch callback and video-update insertions.
    """
    if type(original) is not bytes or type(generated) is not bytes:
        raise ValueError('Source audit requires original and generated bytes')
    blob = git_blob_sha(original)
    if blob != EXPECTED_MAME_BLOB:
        raise ValueError('Unexpected upstream Git blob (not mame0289 CPS-1 video)')
    try:
        src = original.decode('utf-8')
        patched = generated.decode('utf-8')
    except UnicodeError as exc:
        raise ValueError('Upstream and generated C++ must be UTF-8') from exc

    # These checks are intentionally independent from instrument(): its
    # actual output is supplied by the public source-generator CLI.
    if (src.count(INCLUDE) != 1 or src.count(LATCH_HOOK) != 1 or
            src.count(HOOK) != 1 or PROBE_MARKER in src):
        raise ValueError('Unexpected unmodified MAME probe injection anchors')
    if (patched.count(INCLUDE + INCLUDE_ADDITION) != 1 or
            patched.count(LATCH_HOOK + LATCH_ADDITION) != 1 or
            patched.count(VIDEO_UPDATE_ADDITION) != 1 or
            patched.count(PROBE_MARKER) != 1):
        raise ValueError('Generated MAME C++ missing exact approved additions')

    restored = patched.replace(
        INCLUDE + INCLUDE_ADDITION, INCLUDE, 1
    ).replace(
        LATCH_HOOK + LATCH_ADDITION, LATCH_HOOK, 1
    ).replace(
        VIDEO_UPDATE_ADDITION, HOOK, 1
    )
    if restored != src:
        raise ValueError('Generator changed original MAME code outside approved insertions')
    if generated == original:
        raise ValueError('Generated C++ unexpectedly identical to upstream')
    if ('uint16_t observed_obj_words[0x400];' not in PROBE or
            'const unsigned word = observed_obj_words[index];' not in PROBE or
            PROBE.count('m_buffered_obj[index]') != 1 or
            'CPS1_DINO_LATCH_V2 %llu %016llx\\n' not in PROBE):
        raise ValueError('Generated probe lacks single-snapshot OBJ V2 binding')
    return {
        'source_version': 'mamedev/mame tag mame0289',
        'source_git_blob_sha1': blob,
        'source_sha256': hashlib.sha256(original).hexdigest(),
        'generated_sha256': hashlib.sha256(generated).hexdigest(),
        'byte_exact_restoration': True,
        'approved_insertions': 3,
        'actual_upstream_source_compiled': False,
        'original_game_frame_sync_verified': False,
        'pixel_parity_eligible': False,
    }


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('original', type=Path)
    parser.add_argument('generated', type=Path)
    args = parser.parse_args(argv)
    try:
        if args.original.resolve() == args.generated.resolve():
            raise ValueError('Source and generated paths must differ')
        result = audit_original_and_generated(
            args.original.read_bytes(), args.generated.read_bytes())
        import json
        print(json.dumps(result, indent=2))
        return 0
    except (OSError, ValueError) as error:
        print('Real MAME source audit refused:', error, file=sys.stderr)
        return 2


if __name__ == '__main__':
    raise SystemExit(main())
